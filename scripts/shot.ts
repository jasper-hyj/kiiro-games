import puppeteer from 'puppeteer-core'
const [url, w, h, out, touch] = process.argv.slice(2)
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox'] })
const p = await b.newPage()
await p.setViewport({ width: +w, height: +h, deviceScaleFactor: 1, hasTouch: touch === '1', isMobile: touch === '1' })
await p.evaluateOnNewDocument(() => { try { localStorage.setItem('kiiro-lang', 'en') } catch { /* ignore */ } })
await p.goto(url, { waitUntil: 'networkidle0' })
await new Promise((r) => setTimeout(r, 400))
await p.screenshot({ path: out })
await b.close()
