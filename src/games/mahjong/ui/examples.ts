import type { RuleId } from '../engine/rules'

/** Worked winning-hand examples for the rules reference, smallest hands first. The same data is scored by `scripts/examples-test.ts`,
 *  so every hand shown here really wins in the engine with exactly the stated total. Texts are [English, 中文, 日本語]. */
export type Tri = [string, string, string]
export interface Example {
  rule: RuleId
  name: Tri
  /** concealed tiles before the winning tile, in notation: 123m 456p 789s 11z (z: 1-4 winds E S W N, 5 white 6 green 7 red) */
  hand: string
  win: string
  tsumo?: boolean
  riichi?: boolean
  /** called sets (they are shown to the right of the hand) */
  melds?: { type: 'chi' | 'pon' | 'minkan' | 'ankan'; tiles: string }[]
  /** flower kinds held (34 plum … 41 winter) */
  flowers?: number[]
  seat?: number
  voidSuit?: number
  /** Hong Kong / Chinese Official: minimum fan used when scoring the example (default: the ruleset's own, 3 / 8) */
  minFan?: number
  /** what the engine must report: han / fan / tai total, and 1 or 2 for a (double) yakuman */
  total: number
  yakuman?: number
  note: Tri
}

